class Vehiculo {

    constructor(
        id,
        tipo,
        marca,
        modelo,
        anio,
        color,
        asientos,
        chapa,
        costoDia
    ) {
        this.id = id;
        this.tipo = tipo;
        this.marca = marca;
        this.modelo = modelo;
        this.anio = anio;
        this.color = color;
        this.asientos = asientos;
        this.chapa = chapa;
        this.costoDia = costoDia;
        this.disponible = true;
    }
}
